// ================================================

function renderEssays(searchTerm = "") {

  const term = searchTerm.trim().toLocaleLowerCase("pt-BR");

  const filtered = essays
    .map((essay, index) => ({
      ...essay,
      index
    }))
    .filter(essay => {

      return `${essay.title} ${essay.category} ${essay.text}`
        .toLocaleLowerCase("pt-BR")
        .includes(term);

    });

  essayGrid.innerHTML = "";

  filtered.forEach(essay => {

    const card = document.createElement("article");

    card.className = "essay-card";


    const number = document.createElement("span");

    number.className = "essay-number";

    number.textContent = String(essay.index + 1).padStart(2, "0");


    const title = document.createElement("h3");

    title.textContent = essay.title;


    const description = document.createElement("p");

    description.textContent =
      `${essay.category} · ${essay.date}`;


    const button = document.createElement("button");

    button.className = "essay-open";

    button.type = "button";

    button.textContent = "Ler redação ↗";

    button.addEventListener("click", () => openEssay(essay));


    card.append(number, title, description, button);

    essayGrid.appendChild(card);

  });


  essayCount.textContent =
    `${filtered.length} ${
      filtered.length === 1 ? "redação" : "redações"
    }`;

  emptyState.hidden = filtered.length !== 0;

}


